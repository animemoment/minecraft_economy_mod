package com.economymod.zones;

public enum ZoneOrigin {
    /** Сгенерировано миром при создании/загрузке чанка */
    NATURAL,
    /** Создано игроком легально (саженец + костная мука, ведро воды, цветок) */
    PLAYER_CREATED,
    /** Искусственная постройка, не должна считаться зоной для экономики */
    ARTIFICIAL
}